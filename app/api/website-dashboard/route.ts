function count(pattern: RegExp, text: string) {
  return (text.match(pattern) || []).length;
}

function uniqueListingPaths(text: string) {
  const matches = text.match(/\/listing\/[^"'<>\s)]+/g) || [];
  return Array.from(
    new Set(matches.map((path) => path.replace(/[?#].*$/, "")))
  );
}

function titleFrom(text: string) {
  return text.match(/<title>(.*?)<\/title>/i)?.[1] || "";
}

async function fetchText(path: string) {
  const url = path.startsWith("http") ? path : `${SITE_URL}${path}`;
  const started = Date.now();
  try {
    const response = await fetch(url, {
      cache: "no-store",
      headers: {
        "User-Agent": "BVT Website Dashboard/1.0",
      },
      signal: AbortSignal.timeout(9000),
    });
    const text = await response.text();
    return {
      url,
      ok: response.ok,
      status: response.status,
      ms: Date.now() - started,
      text,
      title: titleFrom(text),
      error: null as string | null,
    };
  } catch (error) {
    return {
      url,
      ok: false,
      status: 0,
      ms: Date.now() - started,
      text: "",
      title: "",
      error: error instanceof Error ? error.message : "Unknown fetch error",
    };
  }
}

